// Browser verification of the redesigned navigation and existing planner flows.
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pw = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { chromium } = pw.default || pw;
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox'] } : {});
const results = [];
const check = (name, ok, detail = '') => { results.push({ name, ok: !!ok, detail }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name} ${detail}`); };
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', (e) => errors.push(e.message));
const dialog = () => page.locator('dialog[open]').last();
const nav = async (label) => page.locator('.primary-nav').getByRole('button', { name: new RegExp(label === 'Week' ? 'Calendar' : label === 'Today' ? 'Overview' : label) }).click();
const close = async () => page.keyboard.press('Escape');
const settings = async () => page.getByRole('button', { name: 'Settings', exact: true }).click();
try {
  await page.goto(pathToFileURL(path.join(root, 'dist/margin.html')).href);
  await page.waitForSelector('.calendar-frame');
  check('Calendar is the landing page', await page.locator('.calendar-frame').count() === 1);
  await nav('Today');
  check('only three main navigation choices', await page.locator('.primary-nav button').count() === 3);
  check('advanced options are not on the landing screen', await page.getByRole('tab').count() === 0 && await page.getByRole('button', { name: 'Course data', exact: true }).count() === 0);
  check('uniform background without wallpaper', await page.evaluate(() => getComputedStyle(document.body).backgroundImage === 'none'));
  check('today agenda has titles and real times', await page.locator('.agenda-row').count() > 0 && !(await page.locator('.agenda-list').innerText()).includes('Invalid'));
  check('next action details collapsed initially', !await page.locator('.now-extra').evaluate((e) => e.open));
  await page.locator('.now-extra > summary').click();
  check('location and energy remain accessible', await page.getByLabel('Where you are').isVisible());
  await page.locator('.now-extra > summary').click();
  await page.getByRole('button', { name: 'Start this', exact: true }).click();
  check('session brief works from Today', await dialog().locator('.brief-objective').count() === 1);
  await dialog().getByRole('button', { name: 'Start session', exact: true }).click();
  check('active session appears', /In session since/.test(await page.locator('.now').innerText()));
  await page.getByRole('button', { name: 'Stop without recording' }).click();
  await page.locator('.agenda-row').first().click();
  check('agenda events open details', await dialog().count() === 1); await close();
  await nav('Tasks');
  check('Tasks has its own page', await page.locator('.tasks-workspace').count() === 1 && await page.locator('.now').count() === 0);
  check('task cards are readable and actionable', await page.locator('.task').count() > 0);
  await page.getByRole('button', { name: 'Add task', exact: true }).first().click();
  check('quick task entry uses only three fields', await dialog().locator('input').count() === 3);
  await dialog().getByRole('button', { name: 'Add task', exact: true }).click();
  check('task validation still works', /Give the task a title/.test(await dialog().innerText())); await close();
  await nav('Week');
  check('Week shows seven calendar columns without persistent planning panels', await page.locator('.cal-col').count() === 7 && await page.locator('.side').count() === 0);
  check('walking and study blocks preserved', await page.locator('.cal-travel').count() > 0 && await page.locator('.ev-study').count() > 0);
  const before = await page.locator('.ev-study').count();
  await page.getByRole('button', { name: 'Plan my week', exact: true }).click();
  check('review opens only when needed', await page.locator('.review').count() === 1 && await page.locator('.week-grid .tab').count() === 1);
  check('proposal options and preview blocks render', await page.locator('.opt').count() >= 3 && await page.locator('.ev-proposed').count() > 0);
  await page.getByRole('button', { name: 'Cancel proposal' }).click();
  check('cancel leaves approved plan unchanged', await page.locator('.ev-study').count() === before && await page.locator('.side').count() === 0);
  await page.getByRole('button', { name: 'Plan my week', exact: true }).click();
  await page.locator('.plan-alternatives > summary').click();
  await page.locator('.opt', { hasText: 'Balanced' }).locator('input[type=radio]').check();
  await page.getByRole('button', { name: 'Approve plan', exact: true }).click();
  check('plan approval closes review', await page.locator('.review').count() === 0 && await page.locator('.ev-proposed').count() === 0);
  await page.getByRole('button', { name: 'Review planning details', exact: true }).click();
  check('advanced planning opens on demand', await dialog().getByRole('tab', { name: 'Learning' }).count() === 1);
  await dialog().getByRole('tab', { name: 'Learning' }).click();
  check('learning tab rerenders within dialog', /usable/.test(await dialog().innerText()));
  await dialog().getByRole('tab', { name: 'Try a change' }).click();
  await dialog().getByRole('button', { name: 'Run what-if' }).click();
  check('what-if comparison still works', /With your changes/.test(await dialog().innerText()));
  await dialog().getByRole('tab', { name: 'Stress test' }).click();
  await dialog().getByRole('button', { name: 'Run robustness check' }).click();
  check('robustness check still works', await dialog().locator('.robust li').count() > 0); await close();
  await settings();
  check('settings groups preferences, places, data and imports', /Study preferences/.test(await dialog().innerText()) && /Course data/.test(await dialog().innerText()) && /Backups & data/.test(await dialog().innerText()));
  await dialog().getByRole('button', { name: /Study preferences/ }).click();
  check('preferences open from settings', await dialog().locator('form').count() === 1); await close();
  await settings(); await dialog().getByRole('radio', { name: 'Personal', exact: true }).click();
  check('personal workspace remains separate and empty', await page.locator('.starter').count() === 1);
  await page.getByRole('button', { name: 'Add task', exact: true }).first().click();
  await dialog().locator('input[name=title]').fill('<img src=x> Personal essay');
  await dialog().getByRole('button', { name: 'Add task', exact: true }).click();
  await nav('Tasks');
  check('user content stays text', await page.locator('.task-title', { hasText: '<img src=x>' }).count() === 1 && await page.locator('.task img').count() === 0);
  await page.reload(); await page.waitForSelector('.calendar-frame'); await nav('Tasks');
  check('personal tasks survive refresh', await page.locator('.task-title', { hasText: 'Personal essay' }).count() === 1);
  await settings(); await dialog().getByRole('radio', { name: 'Course demo', exact: true }).click();
  check('mode switching does not copy personal tasks', await page.locator('.task-title', { hasText: 'Personal essay' }).count() === 0);
  await nav('Today'); await page.screenshot({ path: '/tmp/margin-redesign-today.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  check('mobile has no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  check('mobile main navigation visible', await page.locator('.primary-nav').isVisible());
  await page.screenshot({ path: '/tmp/margin-redesign-mobile.png' });
  await nav('Week');
  check('mobile Week displays one day', await page.locator('.cal-col:visible').count() === 1);
  await page.locator('.daychips .chip').nth(2).click();
  check('mobile day switching works', await page.locator('.daychips .chip').nth(2).getAttribute('aria-selected') === 'true');
  await nav('Tasks');
  check('mobile task page has no overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  check('no runtime errors', errors.length === 0, errors.join(' | '));
} catch (e) { check('journey completed', false, e.message); }
finally { await browser.close(); }
fs.writeFileSync(path.join(root, 'docs/smoke-results.json'), JSON.stringify({ ranAt: new Date().toISOString(), passed: results.filter((r) => r.ok).length, failed: results.filter((r) => !r.ok).length, results }, null, 2));
process.exitCode = results.some((r) => !r.ok) ? 1 : 0;
