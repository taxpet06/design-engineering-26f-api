import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pw=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const {chromium}=pw.default||pw;
const browser=await chromium.launch(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']}:{});
const page=await browser.newPage({viewport:{width:1666,height:1000}});
const results=[], errors=[];
page.on('pageerror',e=>errors.push(e.message));
const check=(name,ok)=>{results.push({name,ok:!!ok});console.log(`${ok?'PASS':'FAIL'} ${name}`);};
const dlg=()=>page.locator('dialog[open]').last();
try {
 await page.goto(pathToFileURL(path.join(root,'dist/margin.html')).href); await page.waitForSelector('.calendar-frame');
 check('two-area layout with no right rail',await page.locator('.navigation').isVisible()&&await page.locator('.right-rail').count()===0);
 check('week view shows seven days',await page.locator('.cal-col:visible').count()===7);
 check('no free-window hatching visible',await page.locator('.free-window:visible').count()===0);
 check('dark charcoal background',await page.evaluate(()=>getComputedStyle(document.body).backgroundColor==='rgb(24, 26, 30)'));
 check('rounded solid event blocks',await page.locator('.ev').first().evaluate(e=>getComputedStyle(e).backgroundImage==='none'&&getComputedStyle(e).borderRadius==='7px'));
 check('calendar has more than 600 pixels of height',(await page.locator('.cal-body').boundingBox()).height>=600);
 check('deadline markers are outside event grid',await page.locator('.cal-cols .cal-deadline').count()===0);
 await page.locator('.calendar-view-tabs').getByRole('button',{name:'Day',exact:true}).click();
 check('day view really changes the calendar',await page.locator('.cal-col:visible').count()===1);
 await page.locator('.calendar-view-tabs').getByRole('button',{name:'Week',exact:true}).click();
 check('week view restores seven columns',await page.locator('.cal-col:visible').count()===7);
 await page.locator('.calendar-view-tabs').getByRole('button',{name:'Agenda',exact:true}).click();
 check('agenda is an actual schedule list',await page.locator('.calendar-frame .agenda-section').count()===1&&await page.locator('.calendar-frame .agenda-row').count()>0);
 await page.locator('.calendar-view-tabs').getByRole('button',{name:'Week',exact:true}).click();
 await page.getByRole('button',{name:'Search your planner',exact:true}).click();
 await dlg().getByRole('searchbox').fill('COSC');
 check('search returns source tasks and events',await dlg().locator('.search-result').count()>0);
 await dlg().locator('.search-result').first().click();
 check('search opens editable task details',await dlg().locator('form').count()===1); await page.keyboard.press('Escape');
 await page.keyboard.press('Control+k');
 check('search keyboard shortcut works',await dlg().getByRole('searchbox').count()===1); await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Add event',exact:true}).click();
 check('add event opens a functional form',await dlg().locator('form').count()===1); await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Today',exact:true}).click();
 check('today navigation returns to demo week',(await page.locator('.cal-dayhead').first().locator('.dh-num').innerText()) === '26');
 check('issues remain accessible from toolbar',await page.locator('.toolbar').getByRole('button',{name:/\d+ issues/}).count()===1);
 await page.locator('.primary-nav').getByRole('button',{name:'Tasks',exact:true}).click();
 check('Tasks has one add button',await page.getByRole('button',{name:'Add task',exact:true}).count()===1);
 const before=await page.locator('.task-with-check').count(); await page.locator('.task-with-check input').first().click();
 check('completion checkbox updates task list',await page.locator('.task-with-check').count()===before-1);
 await page.locator('.primary-nav').getByRole('button',{name:'Calendar',exact:true}).click();
 await page.locator('.calendar-view-tabs').getByRole('button',{name:'Day',exact:true}).click();
 const dayBefore=await page.locator('.week-label').innerText(); await page.getByRole('button',{name:'Next period',exact:true}).click();
 check('Day navigation changes date and keeps one column',await page.locator('.week-label').innerText()!==dayBefore&&await page.locator('.cal-col:visible').count()===1);
 await page.locator('.calendar-view-tabs').getByRole('button',{name:'Week',exact:true}).click();
 check('all rendered text uses at least 12px',await page.evaluate(()=>[...document.querySelectorAll('body *')].filter(e=>e.getClientRects().length).every(e=>parseFloat(getComputedStyle(e).fontSize)>=12)));
 await page.screenshot({path:'/tmp/margin-reference-final-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 check('mobile does not overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 check('mobile calendar and day navigation work',await page.locator('.cal-col:visible').count()===1&&await page.locator('.daychips .chip').count()===7);
 await page.screenshot({path:'/tmp/margin-reference-final-mobile.png'});
 check('mobile tools remain accessible',await page.getByRole('button',{name:'Workload',exact:true}).isVisible()&&await page.getByRole('button',{name:'Help',exact:true}).isVisible());
 check('no uncaught runtime errors',errors.length===0);
} catch(e){console.error(e);check('reference journey completed',false);}
finally {await browser.close();}
fs.writeFileSync(path.join(root,'docs/reference-smoke-results.json'),JSON.stringify({ranAt:new Date().toISOString(),results,errors},null,2));
process.exitCode=results.some(r=>!r.ok)?1:0;
