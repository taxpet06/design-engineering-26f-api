import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pw = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { chromium } = pw.default || pw;
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox'] } : {});
const results = [];
const check = (name, ok) => { results.push({ name, ok: !!ok }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}`); };
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', (e) => errors.push(e.message));
const dlg = () => page.locator('dialog[open]').last();
const nav = async (name) => page.locator('.primary-nav').getByRole('button', {name:new RegExp(name === 'Week' ? 'Calendar' : name === 'Today' ? 'Overview' : name)}).click();
const openCourse = async () => { await page.getByRole('button',{name:'Settings',exact:true}).click(); await dlg().getByRole('button',{name:/^Course data/}).click(); };
const mode = async (name) => { await page.getByRole('button',{name:'Settings',exact:true}).click(); await dlg().getByRole('radio',{name,exact:true}).click(); };
try {
  await page.goto(pathToFileURL(path.join(root, 'dist/margin.html')).href);
  await page.waitForSelector('.brand-name');
  await mode('Personal');
  await page.getByRole('button', { name: 'Add task', exact: true }).first().click();
  await dlg().locator('input[name=title]').fill('Keep my personal task');
  await dlg().getByRole('button', { name: 'Add task', exact: true }).click();
  await openCourse();
  check('bundled course snapshot available without network', (await dlg().getByLabel('Demo student').locator('option').count()) === 90);
  await dlg().getByRole('button', { name: 'Preview course import' }).click();
  check('preview states fictional data and missing schedule details', /classes,.*assignments/.test(await dlg().innerText()) && /Unscheduled commitments/.test(await dlg().innerText()));
  await dlg().getByRole('button', { name: 'Replace demo with course data' }).click();
  await page.waitForSelector('dialog[open]');
  check('import opens source report', /Course data details/.test(await dlg().innerText()));
  await page.keyboard.press('Escape'); await nav('Week');
  check('source banner and classes are visible', /Fictional course data/.test(await page.locator('.shell').innerText()) && await page.locator('.ev-fixed').count() > 0);
  await nav('Week'); await page.getByRole('button', { name: 'Plan my week', exact: true }).first().click();
  await page.waitForSelector('.review');
  check('planner works with actual course records', await page.locator('.ev-proposed').count() > 0);
  await page.getByRole('button', { name: 'Approve plan', exact: true }).click();
  check('course plan can be approved', await page.locator('.ev-study').count() > 0);
  await page.reload(); await page.waitForSelector('.brand-name');
  check('import and source report persist across refresh', /Fictional course data/.test(await page.locator('.shell').innerText()));
  await mode('Personal');
  await nav('Tasks');
  check('personal task survived demo import and reload', await page.locator('.task-title', { hasText: 'Keep my personal task' }).count() === 1);
  await mode('Course demo');
  await openCourse();
  const apply = dlg().getByRole('button', { name: 'Replace demo with course data' });
  check('apply disabled until preview', await apply.isDisabled());
  await dlg().getByRole('button', { name: 'Preview course import' }).click();
  await dlg().getByLabel('Default assignment effort in minutes').fill('120');
  check('changing inputs invalidates preview', await apply.isDisabled());
  await dlg().getByLabel('Course demo date').fill('2027-01-01');
  await dlg().getByRole('button', { name: 'Preview course import' }).click();
  check('out-of-term date is rejected', /inside the selected term/.test(await dlg().innerText()) && await apply.isDisabled());
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  check('course demo remains usable on mobile without page overflow', await page.evaluate(() => document.documentElement.scrollWidth - innerWidth <= 1));
  await page.screenshot({ path: '/tmp/margin-course-mobile.png', fullPage: false });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: '/tmp/margin-course-desktop.png', fullPage: false });
  // Offline failure must be explicit, keep old data, and allow a snapshot preview.
  await page.route('https://api-backend-zeta-five.vercel.app/**', (route) => route.abort());
  await openCourse();
  await dlg().getByRole('button', { name: 'Refresh from live API' }).click();
  await page.waitForFunction(() => [...document.querySelectorAll('dialog p')].some((p) => p.textContent.includes('Live refresh failed')));
  check('network failure is explicit; snapshot still works', /snapshot is unchanged/.test(await dlg().innerText()));
  await dlg().getByRole('button', { name: 'Preview course import' }).click();
  check('offline preview remains available after failed refresh', !await dlg().getByRole('button', { name: 'Replace demo with course data' }).isDisabled());
  check('no uncaught course-flow errors', errors.length === 0);
} catch (err) { console.error(err); check(`course journey completed: ${err.message}`, false); }
finally { await browser.close(); }
fs.writeFileSync(path.join(root, 'docs/course-smoke-results.json'), JSON.stringify({ ranAt: new Date().toISOString(), results, errors }, null, 2));
process.exitCode = results.some((r) => !r.ok) ? 1 : 0;
